test("does not lint a tracked lockfile deleted in the working tree", () => {
  const root = createFixture(validNpmFixture());
  try {
    fs.rmSync(path.join(root, "project/package-lock.json"));
    const result = lintRepository(root, { emit: false });
    assert.doesNotMatch(result.errors.join("\n"), /unable to read file/);
    assert.match(result.errors.join("\n"), /found 0/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
