const APPROVED_REGISTRY =
  "https://pkgs.dev.azure.com/ms/react-native/_packaging/react-native-public/npm/registry/";

function dependabot(...directories: string[]): string {
  return `version: 2
updates:
- package-ecosystem: npm
  directories:
${directories.map((directory) => `  - "${directory}"`).join("\n")}
  schedule:
    interval: weekly
`;
}

function validNpmFixture(): Record<string, string> {
  return {
    ".github/dependabot.yml": dependabot("/project"),
    "project/.npmrc": `registry=${APPROVED_REGISTRY}\nomit-lockfile-registry-resolved=true\n`,
    "project/package.json": JSON.stringify({
      name: "npm-fixture",
      version: "1.0.0",
      dependencies: { example: "^1.0.0" },
    }),
    "project/package-lock.json": JSON.stringify({
      name: "npm-fixture",
      version: "1.0.0",
      lockfileVersion: 3,
      requires: true,
      packages: {
        "": {
          name: "npm-fixture",
          version: "1.0.0",
          dependencies: { example: "^1.0.0" },
        },
        "node_modules/example": {
          version: "1.0.0",
          integrity: "sha512-example",
        },
      },
    }),
  };
}

function validYarnFixture(): Record<string, string> {
  return {
    ".github/dependabot.yml": dependabot("/project"),
    ".yarnrc.yml": `nodeLinker: node-modules\nnpmRegistryServer: "${APPROVED_REGISTRY}"\nyarnPath: .yarn/releases/yarn-4.13.0.cjs\n`,
    ".yarn/releases/yarn-4.13.0.cjs": "module.exports = {};\n",
    "project/package.json": JSON.stringify({
      name: "yarn-fixture",
      version: "1.0.0",
      packageManager: "yarn@4.13.0",
      dependencies: { example: "^1.0.0" },
    }),
    "project/yarn.lock": `__metadata:
  version: 8
  cacheKey: 10c0

"example@npm:^1.0.0":
  version: 1.0.0
  resolution: "example@npm:1.0.0"
  checksum: 10c0/example
  languageName: node
  linkType: hard
`,
  };
}

function createFixture(files: Record<string, string>): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "npm-source-lint-"));
  for (const [file, content] of Object.entries(files)) {
    const target = path.join(root, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
  execFileSync("git", ["init", "--quiet", root]);
  execFileSync("git", [
    "-C",
    root,
    "-c",
    "core.autocrlf=false",
    "add",
    "--all",
  ]);
  return root;
}

function removeFile(
  files: Record<string, string>,
  file: string,
): Record<string, string> {
  const result = { ...files };
  delete result[file];
  return result;
}

function assertValid(files: Record<string, string>): void {
  const root = createFixture(files);
  try {
    const result = lintRepository(root, { emit: false });
    assert.deepEqual(result.errors, []);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

function assertViolation(
  files: Record<string, string>,
  expected: RegExp,
): void {
  const root = createFixture(files);
  try {
    const result = lintRepository(root, { emit: false });
    assert.match(result.errors.join("\n"), expected);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

test("detects a Yarn 1 lockfile", () => {
  assert.equal(
    isLegacyYarnLock(
      "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n",
    ),
    true,
  );
});

test("accepts a Yarn 4 lockfile", () => {
  assert.equal(
    isLegacyYarnLock(
      '__metadata:\n  version: 8\n  cacheKey: 10c0\n\n"example@npm:^1.0.0":\n  version: 1.0.0\n',
    ),
    false,
  );
});

test("requires Node.js 24 or newer", () => {
  assert.match(getNodeVersionError("23.11.0") ?? "", /24 or newer/);
  assert.equal(getNodeVersionError("24.0.0"), undefined);
});

test("accepts npm locks with omitted registry URLs", () => {
  assertValid(validNpmFixture());
});

test("rejects an npmjs resolved URL", () => {
  const files = validNpmFixture();
  const lock = JSON.parse(files["project/package-lock.json"]);
  lock.packages["node_modules/example"].resolved =
    "https://registry.npmjs.org/example/-/example-1.0.0.tgz";
  files["project/package-lock.json"] = JSON.stringify(lock);
  assertViolation(files, /registry\.npmjs\.org/);
});

test("rejects another external HTTP tarball", () => {
  const files = validNpmFixture();
  const lock = JSON.parse(files["project/package-lock.json"]);
  lock.packages["node_modules/example"].resolved =
    "https://packages.example.com/example-1.0.0.tgz";
  files["project/package-lock.json"] = JSON.stringify(lock);
  assertViolation(files, /packages\.example\.com/);
});

test("rejects missing npm registry configuration", () => {
  assertViolation(
    removeFile(validNpmFixture(), "project/.npmrc"),
    /committed npm registry configuration is missing/,
  );
});

test("rejects missing omit-lockfile-registry-resolved", () => {
  const files = validNpmFixture();
  files["project/.npmrc"] = `registry=${APPROVED_REGISTRY}\n`;
  assertViolation(files, /omit-lockfile-registry-resolved/);
});

test("rejects an npm scoped registry override", () => {
  const files = validNpmFixture();
  files["project/.npmrc"] +=
    "@example:registry=https://packages.example.com/npm/\n";
  assertViolation(files, /@example:registry/);
});

test("rejects committed npm credentials", () => {
  const files = validNpmFixture();
  files["project/.npmrc"] += "//example.test/:_authToken=secret\n";
  assertViolation(files, /committed npm credentials are forbidden/);
});

